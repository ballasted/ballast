// Generate src/constants/abis.ts from the repo's COMPILED Foundry artifacts
// (contracts/out/<Name>.sol/<Name>.json). ABIs are never hand-written here — run
// `npm run gen:abis` after a `forge build` to refresh. Emitted `as const` so viem
// infers full argument/return/event types in the SDK.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "..", "..", "contracts", "out");

// contract artifact name -> exported const name
const WANT = {
  BallastFactory: "ballastFactoryAbi",
  BallastHook: "ballastHookAbi",
  BackingLens: "backingLensAbi",
  FeeConfig: "feeConfigAbi",
  AssetRegistry: "assetRegistryAbi",
  BuybackBurnerV2: "buybackBurnerV2Abi",
  BasketZap: "basketZapAbi",
  FeeRouterFactory: "feeRouterFactoryAbi",
  FeeRouterFactoryV2: "feeRouterFactoryV2Abi",
  FeeRouterV2: "feeRouterV2Abi",
  ProjectTreasury: "projectTreasuryAbi",
  BallastToken: "ballastTokenAbi",
};

let body = `// GENERATED by scripts/gen-abis.mjs from contracts/out/*.json — DO NOT EDIT BY HAND.\n// Refresh with: npm run gen:abis (after \`forge build\` in /contracts).\n\n`;
for (const [artifact, name] of Object.entries(WANT)) {
  const p = join(OUT, `${artifact}.sol`, `${artifact}.json`);
  if (!existsSync(p)) {
    throw new Error(`Missing compiled artifact: ${p} — run \`forge build\` in /contracts first.`);
  }
  const { abi } = JSON.parse(readFileSync(p, "utf8"));
  body += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
const dest = join(here, "..", "src", "constants", "abis.ts");
writeFileSync(dest, body);
console.log(`Wrote ${dest} (${Object.keys(WANT).length} ABIs)`);
